// Skill-sync v0 — ý tưởng gốc #3: "IDE có thể install skill... và gán cho agent CLI"
// Cơ chế: KB (tầng 3) → render thành AGENTS.md + CLAUDE.md ở repo root.
// Worker CLI đọc file này NGAY KHI chạy (codex đọc AGENTS.md, claude đọc CLAUDE.md)
// — vì worktree checkout từ main nên mọi worker đều nhận phiên bản mới nhất.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { loadKB } from './memory.js';

export interface SyncResult {
  files: string[];
  entries: number;
  pinned: number;
}

export function syncSkills(repo: string): SyncResult {
  const kb = loadKB(repo);
  const pinned = kb.filter((e) => e.pinned);
  const rest = kb.filter((e) => !e.pinned);
  const ordered = [...pinned, ...rest];

  const lines: string[] = [
    '<!-- AUTO-GENERATED by Orchestra skill-sync — KHÔNG sửa tay. Chỉnh `.orchestra/kb/*.md` rồi chạy sync. -->',
    '',
    '# Agent instructions (Orchestra project memory)',
    '',
  ];
  for (const e of ordered) {
    lines.push(`## ${e.title || e.id} \`(${e.id})\``, '', e.text, '');
  }
  const text = lines.join('\n');

  // AGENTS.md: codex + opencode + đa số CLI đọc; CLAUDE.md: claude đọc
  const files = ['AGENTS.md', 'CLAUDE.md'];
  for (const f of files) writeFileSync(path.join(repo, f), text, 'utf8');
  return { files, entries: kb.length, pinned: pinned.length };
}
